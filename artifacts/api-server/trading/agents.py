class PriceActionAgent:
    name = "Price Action Agent"
    emoji = "🕯️"
    method = "Candles + SuperTrend + Pivots + Inside-bar/Key-reversal + BB squeeze + RS vs SPY"

    def analyze(self, df, ind):
        try:
            closes = df["Close"].values
            opens = df["Open"].values
            highs = df["High"].values
            lows = df["Low"].values
            n = len(closes)
            if n < 10:
                return _hold(self.name, self.emoji, "Insufficient data")

            c, o, h, l = closes[-1], opens[-1], highs[-1], lows[-1]
            pc, po = closes[-2], opens[-2]
            ph, pl = highs[-2], lows[-2]
            body = abs(c - o)
            rng = h - l
            bp = body / rng if rng > 0 else 0
            uw = (h - max(c, o)) / rng if rng > 0 else 0
            lw = (min(c, o) - l) / rng if rng > 0 else 0

            signals, reasons = [], []

            # Candlestick patterns
            if c > o and pc < po and c > po and o < pc:
                signals.append("BUY_CALL"); reasons.append("Bullish engulfing")
            if c < o and pc > po and c < po and o > pc:
                signals.append("BUY_PUT"); reasons.append("Bearish engulfing")
            if lw > 0.6 and uw < 0.1 and c >= o:
                signals.append("BUY_CALL"); reasons.append("Hammer reversal")
            if uw > 0.6 and lw < 0.1 and c <= o:
                signals.append("BUY_PUT"); reasons.append("Shooting star")
            if c > o and bp > 0.65 and ind.get("rel_volume", 1) > 1.3:
                signals.append("BUY_CALL"); reasons.append(f"Strong bull candle {ind.get('rel_volume',1):.1f}×vol")
            if c < o and bp > 0.65 and ind.get("rel_volume", 1) > 1.3:
                signals.append("BUY_PUT"); reasons.append(f"Strong bear candle {ind.get('rel_volume',1):.1f}×vol")

            # NEW: Inside-bar break (3-bar continuation pattern)
            # Yesterday's range was inside day-before's range; today breaks one side.
            if n >= 3:
                pph, ppl = highs[-3], lows[-3]
                inside_yesterday = (ph <= pph) and (pl >= ppl)
                if inside_yesterday:
                    if h > ph and c > ph:
                        signals.append("BUY_CALL"); reasons.append("Inside-bar break↑")
                    elif l < pl and c < pl:
                        signals.append("BUY_PUT"); reasons.append("Inside-bar break↓")

            # NEW: 3-bar key reversal (lower-low then strong close above prev high)
            if n >= 3 and l < lows[-2] and c > highs[-2]:
                signals.append("BUY_CALL"); reasons.append("3-bar bullish key reversal")
            if n >= 3 and h > highs[-2] and c < lows[-2]:
                signals.append("BUY_PUT"); reasons.append("3-bar bearish key reversal")

            # NEW: Bollinger Band squeeze breakout
            # Tight BB width then directional close outside the band = expansion.
            bb_width_pct = float(ind.get("bb_width_pct") or 0)
            bb_u = float(ind.get("bb_upper") or c)
            bb_l = float(ind.get("bb_lower") or c)
            if bb_width_pct > 0 and bb_width_pct < 4.0:  # squeezed (<4% of price)
                if c > bb_u and ind.get("rel_volume", 1) > 1.1:
                    signals.append("BUY_CALL"); reasons.append(f"BB squeeze breakout↑ (w={bb_width_pct:.1f}%)")
                elif c < bb_l and ind.get("rel_volume", 1) > 1.1:
                    signals.append("BUY_PUT"); reasons.append(f"BB squeeze breakout↓ (w={bb_width_pct:.1f}%)")

            # Price structure
            if n >= 5:
                if highs[-1] > highs[-5] and lows[-1] > lows[-5]:
                    signals.append("BUY_CALL"); reasons.append("Higher highs + lows (uptrend)")
                elif highs[-1] < highs[-5] and lows[-1] < lows[-5]:
                    signals.append("BUY_PUT"); reasons.append("Lower highs + lows (downtrend)")
            # SuperTrend
            if ind.get("supertrend_dir") == "up":
                signals.append("BUY_CALL"); reasons.append("SuperTrend bullish")
            else:
                signals.append("BUY_PUT"); reasons.append("SuperTrend bearish")
            # Pivot breakout
            pivot_bias = ind.get("pivot_bias", "neutral")
            if pivot_bias == "bullish_breakout":
                signals.append("BUY_CALL"); reasons.append("Pivot R1 breakout")
            elif pivot_bias == "bearish_breakdown":
                signals.append("BUY_PUT"); reasons.append("Pivot S1 breakdown")
            # Ichimoku confirmation
            ichi = ind.get("ichimoku_signal", "neutral")
            if ichi == "bullish": signals.append("BUY_CALL"); reasons.append("Above Ichimoku cloud")
            elif ichi == "bearish": signals.append("BUY_PUT"); reasons.append("Below Ichimoku cloud")

            # NEW: Donchian Channel breakout (Turtle Trader rules — 20-day high/low)
            don = ind.get("donchian") or {}
            if don.get("break") == "bullish":
                signals.append("BUY_CALL"); reasons.append(f"Donchian 20d high break ${don.get('upper')}")
            elif don.get("break") == "bearish":
                signals.append("BUY_PUT"); reasons.append(f"Donchian 20d low break ${don.get('lower')}")

            # NEW: Keltner Channel breakout (EMA20 ± 2×ATR — strong trend signal)
            kel = ind.get("keltner") or {}
            if kel.get("break") == "bullish":
                signals.append("BUY_CALL"); reasons.append("Keltner upper break (trend strength)")
            elif kel.get("break") == "bearish":
                signals.append("BUY_PUT"); reasons.append("Keltner lower break (trend weakness)")

            # NEW: Head & Shoulders / Inverse H&S
            hs = ind.get("head_shoulders", "none")
            if hs == "bullish_inverse":
                signals.append("BUY_CALL"); reasons.append("Inverse H&S neckline break")
            elif hs == "bearish_top":
                signals.append("BUY_PUT"); reasons.append("H&S top neckline break")

            # NEW: Fibonacci bounce signal
            # Price within 0.7% of fib 38.2 / 50 / 61.8 with confirming candle
            near_fib = float(ind.get("near_fib_level") or 0)
            if near_fib > 0:
                dist_pct = abs(c - near_fib) / c * 100
                if dist_pct < 0.7:  # close to a key fib level
                    fib = ind.get("fibonacci") or {}
                    is_golden = abs(near_fib - fib.get("fib_618", 0)) < 0.01 \
                                or abs(near_fib - fib.get("fib_500", 0)) < 0.01 \
                                or abs(near_fib - fib.get("fib_382", 0)) < 0.01
                    if is_golden:
                        if c > o and lw > 0.3:  # bullish reversal candle off support
                            signals.append("BUY_CALL"); reasons.append(f"Fib bounce ${near_fib:.2f}")
                        elif c < o and uw > 0.3:  # bearish rejection at fib
                            signals.append("BUY_PUT"); reasons.append(f"Fib reject ${near_fib:.2f}")

            # NEW: Parabolic SAR
            psar = ind.get("psar") or {}
            if psar.get("trend") == "up":
                signals.append("BUY_CALL"); reasons.append("PSAR flipped bullish")
            elif psar.get("trend") == "down":
                signals.append("BUY_PUT"); reasons.append("PSAR flipped bearish")

            # NEW: Aroon
            aroon = ind.get("aroon") or {}
            aoz = float(aroon.get("osc") or 0)
            if aoz > 50:
                signals.append("BUY_CALL"); reasons.append(f"Aroon osc +{aoz:.0f}")
            elif aoz < -50:
                signals.append("BUY_PUT"); reasons.append(f"Aroon osc {aoz:.0f}")

            # NEW: Double top / bottom
            dpat = ind.get("double_pattern", "none")
            if dpat == "double_bottom":
                signals.append("BUY_CALL"); reasons.append("Double bottom break")
            elif dpat == "double_top":
                signals.append("BUY_PUT"); reasons.append("Double top break")

            # NEW: Triangle pattern
            tpat = ind.get("triangle_pattern", "none")
            if tpat == "ascending":
                signals.append("BUY_CALL"); reasons.append("Ascending triangle")
            elif tpat == "descending":
                signals.append("BUY_PUT"); reasons.append("Descending triangle")

            # NEW: Cup & Handle breakout
            if ind.get("cup_handle") == "cup_handle":
                signals.append("BUY_CALL"); reasons.append("Cup & handle break")

            # NEW: Kalman-smoothed trend slope
            kalman = ind.get("kalman_trend") or {}
            kslope = float(kalman.get("slope_pct") or 0)
            if kslope > 1.5:
                signals.append("BUY_CALL"); reasons.append(f"Kalman trend +{kslope:.1f}%")
            elif kslope < -1.5:
                signals.append("BUY_PUT"); reasons.append(f"Kalman trend {kslope:.1f}%")

            # NEW: Relative strength vs SPY
            # If this stock outperformed SPY by >0.6% today → bullish RS,
            # underperformed by >0.6% → bearish RS. Strong directional edge
            # because it tells us the stock has its own momentum.
            spy = ind.get("spy_trend") or {}
            spy_chg = float(spy.get("change_1d") or 0)
            stock_chg = float(ind.get("change_1d") or 0)
            rs_diff = stock_chg - spy_chg
            if abs(rs_diff) >= 0.6 and spy.get("dir") != "self":
                if rs_diff > 0:
                    signals.append("BUY_CALL"); reasons.append(f"RS vs SPY +{rs_diff:.1f}%")
                else:
                    signals.append("BUY_PUT"); reasons.append(f"RS vs SPY {rs_diff:.1f}%")

            calls = signals.count("BUY_CALL")
            puts = signals.count("BUY_PUT")
            total = max(calls + puts, 1)
            conf = 55 + (max(calls, puts) / total) * 30
            r = " | ".join(reasons[:3])
            if calls > puts:
                return _vote(self.name, self.emoji, "BUY_CALL", conf, r)
            elif puts > calls:
                return _vote(self.name, self.emoji, "BUY_PUT", conf, r)
            return _hold(self.name, self.emoji, r or "No clear pattern")
        except Exception as e:
            return _hold(self.name, self.emoji, f"Error: {e}")


