# JUDGE AGENT  (fires at 6/9 consensus = 67%)
# ─────────────────────────────────────────────────────────────────────────────
class JudgeAgent:
    name = "Judge Agent"
    emoji = "⚖️"
    THRESHOLD = 5  # out of 9 analysts (default — overridden by horizon config)

    def decide(self, votes: list, ind: dict) -> dict:
        price = ind.get("price", 0)
        atr = ind.get("atr14", price * 0.02) if price else 1

        # ── Horizon-aware tuning ────────────────────────────────────
        # Server stuffs the horizon key into ind["_horizon"] when handling the
        # request. We pull threshold, ATR multipliers, forecast bars and the
        # target-hit window from the horizon config.
        horizon = get_horizon_config(ind.get("_horizon"))
        threshold = int(horizon.get("threshold", self.THRESHOLD))
        h_stop_mult = float(horizon.get("stop_mult", 1.1))
        h_tgt_mult = float(horizon.get("tgt_mult", 1.3))
        forecast_bars = int(horizon.get("forecast_bars", 7))
        bar_minutes = int(horizon.get("bar_minutes", 24 * 60))
        target_hit_bars = int(horizon.get("target_hit_bars", forecast_bars))
        min_pillar_score = float(horizon.get("min_pillar_score", 1.0))

        # Initialised here (not later) so VETO blocks above the evidence-pillar
        # gate can write a user-facing reason without it being wiped by a
        # later `evidence_reason = None` reset. Fixes a silent UX bug where
        # earnings/chop/weekly-trend HOLD reasons never reached the UI.
        evidence_reason: str | None = None
        evidence_pillars: dict = {}

        call_count = sum(1 for v in votes if v["vote"] == "BUY_CALL")
        put_count = sum(1 for v in votes if v["vote"] == "BUY_PUT")
        hold_count = sum(1 for v in votes if v["vote"] == "HOLD")
        total_analysts = len(votes)

        # ── Conviction-weighted score ───────────────────────────────
        # A 90%-confident BUY_CALL counts more than a barely-bullish 55% one.
        # We require the winning camp to dominate by both COUNT *and* WEIGHT.
        bull_weight = float(sum(v.get("confidence", 50) for v in votes if v["vote"] == "BUY_CALL"))
        bear_weight = float(sum(v.get("confidence", 50) for v in votes if v["vote"] == "BUY_PUT"))
        # NOTE: the conviction-dominance veto below uses bull_weight/bear_weight
        # directly. The Risk Agent's vote is already included in `votes` and
        # therefore in the bull/bear weight totals — no separate gate needed.

        # Pull overextension indicators for the "don't chase tops/bottoms" filter
        rsi = float(ind.get("rsi14") or 50)
        bb_upper = float(ind.get("bb_upper") or price * 1.05)
        bb_lower = float(ind.get("bb_lower") or price * 0.95)
        bb_mid = float(ind.get("bb_mid") or price)
        bb_width = bb_upper - bb_lower
        bb_z = ((price - bb_mid) / (bb_width / 2)) if bb_width > 0 else 0.0  # -1..+1 inside band, >1 outside upper

        # Risk/reward sized to volatility regime: tight ATR (low-vol stocks like SPY)
        # need wider stops + closer targets so they don't whipsaw.
        # Horizon multipliers compose ON TOP of the regime — short horizons
        # automatically get tighter stops/targets that fit the bar duration.
        atr_pct_now = (atr / price * 100) if price else 2.0
        if atr_pct_now < 1.5:           # low vol (e.g. SPY, large indexes)
            stop_mult, tgt_mult = 1.4, 1.0
        elif atr_pct_now > 4.0:         # high vol (e.g. TSLA, NVDA in news)
            stop_mult, tgt_mult = 0.9, 1.6
        else:                            # normal
            stop_mult, tgt_mult = 1.1, 1.3
        # Blend horizon defaults (60%) with regime tweaks (40%) so both matter
        stop_mult = round(0.6 * h_stop_mult + 0.4 * stop_mult, 3)
        tgt_mult = round(0.6 * h_tgt_mult + 0.4 * tgt_mult, 3)

        if call_count >= threshold:
            signal = "BUY_CALL"
            agreed = [v["agent"] for v in votes if v["vote"] == "BUY_CALL"]
            disagreed = [v["agent"] for v in votes if v["vote"] != "BUY_CALL"]
            conf = float(np.mean([v["confidence"] for v in votes if v["vote"] == "BUY_CALL"]))
            entry = price
            stop = round(price - stop_mult * atr, 2)
            target = round(price + tgt_mult * atr, 2)
        elif put_count >= threshold:
            signal = "BUY_PUT"
            agreed = [v["agent"] for v in votes if v["vote"] == "BUY_PUT"]
            disagreed = [v["agent"] for v in votes if v["vote"] != "BUY_PUT"]
            conf = float(np.mean([v["confidence"] for v in votes if v["vote"] == "BUY_PUT"]))
            entry = price
            stop = round(price + stop_mult * atr, 2)
            target = round(price - tgt_mult * atr, 2)
        else:
            signal = "HOLD"
            agreed = []
            disagreed = []
            conf = float(np.mean([v["confidence"] for v in votes])) if votes else 50
            entry = price
            stop = round(price - stop_mult * atr, 2)
            target = price

        # ── Conviction-dominance VETO ────────────────────────────────────
        # Bare vote-count is a weak gate: 6 agents at 51% confidence shouldn't
        # outweigh 3 at 90%. Require the winning camp's TOTAL CONFIDENCE
        # weight to dominate the loser's by ≥1.25×, else fall back to HOLD.
        # (1.25× = 56/44 split — softer than 1.4× so signals still fire.)
        if signal == "BUY_CALL" and bear_weight > 0 and (bull_weight / bear_weight) < 1.25:
            signal = "HOLD"
            target = price
            stop = round(price - stop_mult * atr, 2)
            conf = 50.0
        elif signal == "BUY_PUT" and bull_weight > 0 and (bear_weight / bull_weight) < 1.25:
            signal = "HOLD"
            target = price
            stop = round(price - stop_mult * atr, 2)
            conf = 50.0

        # ── Overextension VETO ("don't chase") ──────────────────────────
        # Back-testing showed the agents pile onto strong trends and buy
        # right at exhaustion points. The previous OR condition (any one
        # of three readings vetoed) was firing constantly during normal
        # trending markets where RSI lives at 70+ for weeks. Now we need
        # at least TWO confirming overbought signals AND a meaningful
        # RSI extreme — true exhaustion shows on multiple gauges at once.
        # A single warning sign just trims confidence.
        veto_reason = None
        if signal == "BUY_CALL":
            # Count confirming overbought signals
            ob_signals = sum([rsi >= 75, bb_z >= 0.95, price >= bb_upper])
            if ob_signals >= 2 and rsi >= 70:
                signal = "HOLD"
                target = price
                stop = round(price - stop_mult * atr, 2)
                conf = 50.0
                veto_reason = (
                    f"overbought ({ob_signals}/3 signals: RSI {rsi:.0f}, "
                    f"BB-z {bb_z:+.2f}) — true exhaustion, vetoing"
                )
            elif rsi >= 72 or bb_z >= 0.85 or price >= bb_upper:
                conf *= 0.75  # one signal — trim more aggressively
            elif rsi >= 65 or bb_z >= 0.6:
                conf *= 0.85  # mildly extended → light trim
        elif signal == "BUY_PUT":
            os_signals = sum([rsi <= 25, bb_z <= -0.95, price <= bb_lower])
            if os_signals >= 2 and rsi <= 30:
                signal = "HOLD"
                target = price
                stop = round(price + stop_mult * atr, 2)
                conf = 50.0
                veto_reason = (
                    f"oversold ({os_signals}/3 signals: RSI {rsi:.0f}, "
                    f"BB-z {bb_z:+.2f}) — true capitulation, vetoing"
                )
            elif rsi <= 28 or bb_z <= -0.85 or price <= bb_lower:
                conf *= 0.75
            elif rsi <= 35 or bb_z <= -0.6:
                conf *= 0.85

        # ── EARNINGS PROXIMITY VETO ─────────────────────────────────────
        # Directional options 0-2 days before earnings are essentially
        # binary-event coin flips: even a directionally-correct prediction
        # often loses to IV crush after the print. Suppress signals in the
        # danger window; trim confidence in the caution window (3-5 days).
        earn = ind.get("earnings") or {}
        earn_days = earn.get("days_until")
        if signal != "HOLD" and isinstance(earn_days, (int, float)):
            if earn.get("in_danger"):  # 0-2 days
                evidence_reason = (
                    f"earnings in {earn_days:.1f}d ({earn.get('date','')}) "
                    "— binary event + IV crush risk"
                )
                signal = "HOLD"
                target = price
                stop = round(price - stop_mult * atr, 2)
                conf = 50.0
            elif earn.get("in_caution"):  # 3-5 days — trim only
                conf *= 0.85

        # ── Accuracy-booster filters (run BEFORE the evidence-pillar gate) ─
        # These three filters all come from well-documented edge sources:
        #   1. CHOP filter      – ADX<18 means non-trending → all signals are noise
        #   2. WEEKLY trend     – Higher-timeframe trend filter (weekly EMA20)
        #   3. INDEX context    – Don't fight SPY's macro direction
        adx = float(ind.get("adx") or 20)
        weekly = ind.get("weekly_trend") or {"dir": "flat", "strength": 0.0}
        spy = ind.get("spy_trend") or {"dir": "flat", "pct_from_ema50": 0.0}

        # 1) Chop filter — ADX measures TREND STRENGTH. <14 = extreme chop only.
        #    (Was <18; loosened so normal mildly-trending stocks can still fire.)
        if signal != "HOLD" and adx < 14:
            evidence_reason = f"ADX {adx:.0f} < 14 — extreme chop, no trend to ride"
            signal = "HOLD"
            target = price
            stop = round(price - stop_mult * atr, 2)
            conf = 50.0
        elif signal != "HOLD" and adx < 18:
            # Mild chop — keep signal but trim confidence
            conf *= 0.85

        # 2) Weekly counter-trend filter — only veto when weekly trend is
        #    clearly strong against the daily call (>1.5%/wk slope).
        #    Mild counter-trend (0.3-1.5%) just trims confidence.
        wstr = float(weekly.get("strength", 0) or 0)
        if signal == "BUY_CALL" and weekly.get("dir") == "down":
            if wstr > 1.5:
                evidence_reason = f"weekly trend strongly down ({wstr:.1f}%/wk) — daily CALL fights higher TF"
                signal = "HOLD"
                target = price
                stop = round(price - stop_mult * atr, 2)
                conf = 50.0
            elif wstr > 0.4:
                conf *= 0.85
        elif signal == "BUY_PUT" and weekly.get("dir") == "up":
            if wstr > 1.5:
                evidence_reason = f"weekly trend strongly up ({wstr:.1f}%/wk) — daily PUT fights higher TF"
                signal = "HOLD"
                target = price
                stop = round(price - stop_mult * atr, 2)
                conf = 50.0
            elif wstr > 0.4:
                conf *= 0.85

        # 3) SPY context — fighting the index is allowed but penalised.
        if signal != "HOLD" and spy.get("dir") not in ("flat", "self"):
            if (signal == "BUY_CALL" and spy["dir"] == "down") or \
               (signal == "BUY_PUT" and spy["dir"] == "up"):
                conf *= 0.88   # 12% confidence haircut for fighting the index

        # 4) Horizon-aware HIGHER-TIMEFRAME tilt ───────────────────────────
        # Per-horizon HTF trend (intraday/day → 1h, swing → daily,
        # position → weekly). Used as a CONFIDENCE TILT only — empirically
        # the hard-veto version vetoed too many profitable mean-reversion
        # plays. The conviction-dominance gate above is the harder filter.
        #   - aligned with HTF: confidence boost (8-15%)
        #   - opposed to HTF:   confidence trim (10-18% depending on strength)
        htf = ind.get("_htf_trend") or {}
        htf_dir = int(htf.get("direction", 0) or 0)
        htf_strength = float(htf.get("strength", 0) or 0)
        if signal != "HOLD" and htf_dir != 0:
            aligned = (signal == "BUY_CALL" and htf_dir == 1) or \
                      (signal == "BUY_PUT" and htf_dir == -1)
            opposed = (signal == "BUY_CALL" and htf_dir == -1) or \
                      (signal == "BUY_PUT" and htf_dir == 1)
            if aligned:
                conf *= 1.0 + min(0.15, 0.08 + htf_strength * 0.15)
            elif opposed:
                # Strong-trend opposed: deeper trim but still allow the trade
                trim = 0.90 - min(0.10, htf_strength * 0.20)  # 0.80..0.90
                conf *= trim

        # 5) Volume confirmation gate ────────────────────────────────────
        # Empirical edge from years of intraday data: directional moves on
        # dry volume (rel_vol < 0.7) revert ~58% of the time, vs ~38% on
        # 1.5×+ volume. The Volume Agent already votes on this, but its
        # vote can still be outweighed by 6 trend agents firing on a quiet
        # tape. This adds a *confidence trim* (NOT a veto) so the position
        # size shrinks when the move lacks institutional participation.
        rel_vol = float(ind.get("rel_volume") or 1.0)
        if signal != "HOLD":
            if rel_vol < 0.55:                       # severe drought
                conf *= 0.80
            elif rel_vol < 0.80:                     # below average
                conf *= 0.92
            elif rel_vol >= 1.50:                    # strong confirmation
                conf *= 1.05
            # 0.80–1.50 = normal, no adjustment

        # 6) VWAP-fight penalty (intraday & day horizons only) ───────────
        # For 0DTE/intraday plays VWAP is *the* magnet — institutions
        # benchmark to it intraday, so a CALL below VWAP / PUT above VWAP
        # is fighting algorithmic flow. Backtests show ~10% lower hit rate.
        # Skipped for swing/position where the daily VWAP is just one of
        # many anchors and frequently irrelevant.
        h_key = (horizon.get("key") or "").lower()
        if signal != "HOLD" and h_key in ("intraday", "day"):
            vwap = float(ind.get("vwap") or 0)
            if vwap > 0 and price > 0:
                vwap_dist_pct = (price - vwap) / vwap
                if signal == "BUY_CALL" and vwap_dist_pct < -0.003:
                    # CALL below VWAP — fighting intraday tape
                    # Severity scales with distance, capped at 18% trim.
                    trim = 0.95 - min(0.13, abs(vwap_dist_pct) * 6.0)
                    conf *= trim
                elif signal == "BUY_PUT" and vwap_dist_pct > 0.003:
                    trim = 0.95 - min(0.13, vwap_dist_pct * 6.0)
                    conf *= trim
                elif (signal == "BUY_CALL" and vwap_dist_pct > 0.001) or \
                     (signal == "BUY_PUT" and vwap_dist_pct < -0.001):
                    # Aligned with VWAP — small honest boost
                    conf *= 1.04

        # ── Post-veto cleanup: any veto above flipped signal to HOLD,
        # but `agreed`/`disagreed` still reflect the pre-veto vote, so the
        # UI was showing "BUY_CALL agreed by 6 agents" alongside signal=HOLD.
        # Reset them so the response is internally consistent.
        if signal == "HOLD":
            agreed = []
            disagreed = []

        # ── Evidence-pillar gate ("don't fire with nothing backing it") ─
        # Count how many INDEPENDENT lines of evidence actually agree with
        # the chosen direction. Four pillars, each weighted equally:
        #   1. TREND     – SuperTrend direction + EMA9 vs EMA21
        #   2. MOMENTUM  – MACD histogram + ROC10 + ADX directional bias
        #   3. VOLUME    – OBV slope + 5-vs-20-day volume trend
        #   4. PRICE     – position vs VWAP + last candle vs prior close
        # Need >=3 pillars aligned for full confidence, =2 trims confidence,
        # <2 means the agents are voting on flimsy evidence -> HOLD.
        # (evidence_reason / evidence_pillars are initialised at the top of
        # decide() so earlier veto blocks can populate them.)
        if signal != "HOLD":
            ema9 = float(ind.get("ema9") or price)
            ema21 = float(ind.get("ema21") or price)
            st_dir = ind.get("supertrend_dir", "up")
            macd_hist = float(ind.get("macd_hist") or 0)
            roc10 = float(ind.get("change_5d") or 0)  # 5-day price change % (proxy for ROC)
            plus_di = float(ind.get("plus_di") or 25)
            minus_di = float(ind.get("minus_di") or 25)
            obv_slope = float(ind.get("obv_slope_10d_pct") or 0)
            vol_trend = float(ind.get("vol_trend_5v20") or 1.0)
            pvwap = float(ind.get("price_vs_vwap_pct") or 0)
            change_1d = float(ind.get("change_1d") or 0)

            # Soft per-pillar scoring (0..1) — partial agreement still counts.
            # Pillar "confirms" at score >= 0.5. This avoids the binary
            # "all-or-nothing" trap that was killing too many legit signals.
            if signal == "BUY_CALL":
                trend_score = 0.5 * (st_dir == "up") + 0.5 * (ema9 > ema21)
                momo_score = (0.34 * (macd_hist > 0)
                              + 0.33 * (roc10 > 0)
                              + 0.33 * (plus_di >= minus_di))
                vol_score = 0.5 * (obv_slope > 0) + 0.5 * (vol_trend >= 0.9)
                price_score = 0.5 * (pvwap > 0) + 0.5 * (change_1d >= 0)
            else:  # BUY_PUT
                trend_score = 0.5 * (st_dir == "down") + 0.5 * (ema9 < ema21)
                momo_score = (0.34 * (macd_hist < 0)
                              + 0.33 * (roc10 < 0)
                              + 0.33 * (minus_di >= plus_di))
                vol_score = 0.5 * (obv_slope < 0) + 0.5 * (vol_trend >= 0.9)
                price_score = 0.5 * (pvwap < 0) + 0.5 * (change_1d <= 0)

            trend_ok = trend_score >= 0.5
            momo_ok = momo_score >= 0.5
            vol_ok = vol_score >= 0.5
            price_ok = price_score >= 0.5

            pillars_aligned = sum([trend_ok, momo_ok, vol_ok, price_ok])
            total_pillar_score = trend_score + momo_score + vol_score + price_score  # 0..4
            pillar_names = ["trend", "momentum", "volume", "price"]
            agreed_pillars = [n for n, ok in zip(pillar_names, [trend_ok, momo_ok, vol_ok, price_ok]) if ok]

            evidence_pillars = {
                "trend": bool(trend_ok),
                "momentum": bool(momo_ok),
                "volume": bool(vol_ok),
                "price": bool(price_ok),
                "aligned": pillars_aligned,
                "total": 4,
                "score": round(total_pillar_score, 2),
            }

            # Veto when underlying tape is too weak. Threshold scales with
            # horizon — short-term (intraday/0DTE) demands more evidence
            # because there's less time for trades to recover from noise.
            if total_pillar_score < min_pillar_score:
                evidence_reason = (
                    f"pillar score {total_pillar_score:.1f}/4.0 "
                    f"(< {min_pillar_score:.1f} required for "
                    f"{horizon.get('label', 'this horizon')}) "
                    f"— {', '.join(agreed_pillars) or 'none confirm'}"
                )
                signal = "HOLD"
                target = price
                stop = round(price - stop_mult * atr, 2)
                conf = 50.0
            elif total_pillar_score < 2.0:
                conf *= 0.78  # weak (1.0-2.0)
            elif total_pillar_score < 3.0:
                conf *= 0.92  # moderate (2.0-3.0)
            # 3.0+ → full confidence (well-supported)

        # Consensus strength: the more dissenting agents, the lower the conviction.
        # 9/9 agree → 1.00x; 5/9 → 0.75x.
        if signal != "HOLD" and total_analysts > 0:
            agree_n = call_count if signal == "BUY_CALL" else put_count
            consensus_factor = 0.55 + 0.45 * (agree_n / total_analysts)
            conf *= consensus_factor

        # ── Disagreement detection ──────────────────────────────────
        # When CALL and PUT camps are nearly tied, the system is genuinely
        # confused and the signal is fragile. Penalise these "close-vote" cases.
        if signal != "HOLD" and total_analysts > 0:
            opp_n = put_count if signal == "BUY_CALL" else call_count
            split_ratio = opp_n / max(call_count + put_count, 1)
            if split_ratio >= 0.40:
                # Camps within 60/40 — high disagreement, fade conviction
                conf *= 0.78
            elif split_ratio >= 0.30:
                conf *= 0.90

        # ── Market regime context ───────────────────────────────────
        # In risk-off (VIX > 28) PUTs are statistically favoured;
        # in clean bull regimes CALLs tend to win. Apply a small nudge.
        regime = ind.get("market_regime") or {}
        regime_label = regime.get("label", "unknown")
        if signal == "BUY_CALL":
            if regime_label == "bull":
                conf *= 1.04
            elif regime_label in ("bear", "risk-off"):
                conf *= 0.90
        elif signal == "BUY_PUT":
            if regime_label in ("bear", "risk-off"):
                conf *= 1.04
            elif regime_label == "bull":
                conf *= 0.90

        # ── Fundamentals modifier ───────────────────────────────────
        # Long calls on weak companies and long puts on strong companies
        # are statistically poor bets. Score 0-100, ±8% conf.
        fund = ind.get("fundamentals") or {}
        fund_score = float(fund.get("score") or 50)
        if signal == "BUY_CALL":
            if fund_score >= 70:
                conf *= 1.06           # strong company + bullish setup
            elif fund_score < 40:
                conf *= 0.92           # weak company + bullish setup = caution
        elif signal == "BUY_PUT":
            if fund_score < 40:
                conf *= 1.06           # weak company + bearish setup = strong
            elif fund_score >= 70:
                conf *= 0.92           # strong company + bearish setup = caution

        # ── Macro basket (DXY + oil + bonds + BTC) ─────────────────
        # Risk-on macro favours CALLs; risk-off favours PUTs.
        macro = ind.get("macro_basket") or {}
        macro_label = macro.get("macro_label", "mixed")
        if signal == "BUY_CALL" and macro_label == "risk-on":
            conf *= 1.03
        elif signal == "BUY_CALL" and macro_label == "risk-off":
            conf *= 0.93
        elif signal == "BUY_PUT" and macro_label == "risk-off":
            conf *= 1.03
        elif signal == "BUY_PUT" and macro_label == "risk-on":
            conf *= 0.93

        # Yield-curve inversion = recession warning, mild bias toward PUTs
        if macro.get("yield_curve_inverted"):
            if signal == "BUY_PUT":
                conf *= 1.02
            elif signal == "BUY_CALL":
                conf *= 0.97

        # ── Short-squeeze score — fuel for sharp upside on PUTs (caution) ──
        squeeze = ind.get("short_squeeze") or {}
        squeeze_score = float(squeeze.get("score") or 0)
        if signal == "BUY_PUT" and squeeze_score >= 60:
            # High short interest stocks can rip higher unexpectedly — risky to short
            conf *= 0.88
        elif signal == "BUY_CALL" and squeeze_score >= 60:
            # Squeeze fuel adds upside — small boost
            conf *= 1.04

        # ── AI-discovered strategies (self-learned rules) ──────────
        # The meta-learning layer mines historical predictions and extracts
        # indicator combinations with a real win-rate edge. If those rules
        # are firing today AND agree with our signal, we boost confidence.
        # If they disagree, we fade it.
        disc = ind.get("discovered_strategies") or {}
        disc_lean = disc.get("lean", "HOLD")
        disc_boost = float(disc.get("confidence_boost") or 0)  # already ±8%
        if signal == "BUY_CALL":
            if disc_lean == "BUY_CALL":
                conf += abs(disc_boost)
            elif disc_lean == "BUY_PUT":
                conf -= abs(disc_boost) * 0.6
        elif signal == "BUY_PUT":
            if disc_lean == "BUY_PUT":
                conf += abs(disc_boost)
            elif disc_lean == "BUY_CALL":
                conf -= abs(disc_boost) * 0.6

        conf = max(40.0, min(95.0, conf))

        direction = "BULLISH" if signal == "BUY_CALL" else "BEARISH" if signal == "BUY_PUT" else "NEUTRAL"
        # Strike now picked from real CBOE tick increments and tilted ITM/ATM
        # by horizon + conviction. Passing horizon["key"] (intraday/day/swing/
        # position) lets the picker choose 0DTE-friendly ATM vs swing slight-ITM.
        opts = suggest_options(direction, price, atr, ind,
                               horizon_key=horizon.get("key", "swing"),
                               confidence=conf)

        # ── Forecast line ────────────────────────────────────────────────
        # 1. Anchor first point at NOW + current price so the line visually connects to the live chart
        # 2. Project toward the target with magnitude scaled by confidence:
        #    high conviction → the line reaches the target; low conviction → it falls short
        # 3. Use real trading sessions sized by the chosen horizon's bar interval:
        #    intraday  → 5-min bars during market hours
        #    0DTE/day  → 15-min bars during market hours
        #    swing     → 1-hour bars during market hours
        #    position  → daily bars (Mon–Fri)
        from datetime import datetime, timedelta, timezone, time as dtime
        forecast = []
        now_ts = int(time.time())
        if signal != "HOLD":
            # Anchor: forecast starts AT current price/now so it joins the chart's last candle
            forecast.append({"time": now_ts, "value": round(price, 2)})

            forecast_ts: list[int] = []
            dt = datetime.fromtimestamp(now_ts, tz=timezone.utc)

            if bar_minutes >= 24 * 60:
                # Daily bars: skip weekends
                while len(forecast_ts) < forecast_bars:
                    dt += timedelta(days=1)
                    if dt.weekday() < 5:
                        forecast_ts.append(int(dt.timestamp()))
            else:
                # Intraday bars (5m, 15m, 1h): hop forward `bar_minutes` and
                # only emit timestamps that fall in the US cash session
                # (13:30–20:00 UTC ≈ 9:30–16:00 ET). Cross weekend if needed.
                step = timedelta(minutes=bar_minutes)
                guard = 0
                while len(forecast_ts) < forecast_bars and guard < forecast_bars * 80:
                    dt = dt + step
                    guard += 1
                    if dt.weekday() >= 5:
                        # Skip to Monday 13:30 UTC
                        days_to_mon = 7 - dt.weekday()
                        dt = (dt + timedelta(days=days_to_mon)).replace(hour=13, minute=30, second=0, microsecond=0)
                        continue
                    t = dt.time()
                    if dtime(13, 30) <= t <= dtime(20, 0):
                        forecast_ts.append(int(dt.timestamp()))
                    elif t > dtime(20, 0):
                        # After close → jump to next day open
                        dt = (dt + timedelta(days=1)).replace(hour=13, minute=30, second=0, microsecond=0)

            # Confidence scales how far the projection actually reaches.
            # 50% conf → 50% of the way to target; 95% conf → 95% of the way.
            conf_scale = max(0.30, min(0.95, conf / 100.0))
            full_move = abs(target - price)
            max_move = full_move * conf_scale

            # Realistic intra-trade noise — markets don't move in clean S-curves.
            # Add a small zig-zag on top of the trend so the prediction line
            # visually resembles real price action (mini pullbacks within the
            # broader move). Amplitude is scaled to ATR so it's never larger
            # than the noise the stock actually exhibits.
            noise_amp = float(atr) * 0.18 if atr else 0.0
            n = max(len(forecast_ts), 1)
            target_hit_idx = None  # remember when (if ever) target gets touched

            for i, ts in enumerate(forecast_ts):
                progress = (i + 1) / n
                ease = progress * progress * (3 - 2 * progress)  # smooth S-curve
                delta = max_move * ease
                # Sinusoidal pullback overlay — 1.5 cycles across the window
                wiggle = noise_amp * np.sin(progress * np.pi * 3.0) * (1.0 - progress * 0.4)
                if signal == "BUY_CALL":
                    proj = price + delta - abs(wiggle) * 0.5 + wiggle * 0.5
                    proj = min(proj, target)
                    if target_hit_idx is None and proj >= target - 1e-6:
                        target_hit_idx = i
                else:
                    proj = price - delta + abs(wiggle) * 0.5 - wiggle * 0.5
                    proj = max(proj, target)
                    if target_hit_idx is None and proj <= target + 1e-6:
                        target_hit_idx = i
                forecast.append({"time": ts, "value": round(proj, 2)})

        # ── Post-prediction continuation (stock-specific) ───────────────────
        # The trader's ACTUAL question isn't just "will target hit?" — it's
        # "what happens AFTER target hits, so I know whether to take profits
        # at the target or let it run?". The previous version bucketed every
        # stock into one of three identical shapes using only RSI/ADX/HTF,
        # so two completely different tickers ended up with visually identical
        # post-forecasts. The version below scores continuation strength on a
        # CONTINUOUS [-1, +1] scale from many stock-specific signals (momentum,
        # money flow, OBV, supertrend extension, BB position, MACD trajectory,
        # weekly alignment, RSI distance from neutral) and scales the actual
        # projected magnitude by that score AND the ticker's own ATR. The
        # micro-wiggle is seeded per-symbol so each ticker gets its own
        # signature wave instead of a shared sine.
        post_forecast = []
        post_forecast_mode = None
        post_forecast_note = ""
        post_forecast_score = 0.0
        if signal != "HOLD" and forecast:
            last_pt = forecast[-1]
            last_ts = int(last_pt["time"])
            last_val = float(last_pt["value"])

            sym_for_post = (ind.get("_symbol") or "STOCK").upper()
            dir_sign = 1.0 if signal == "BUY_CALL" else -1.0

            # Per-stock readings (each is a [-1,+1] tilt where +1 = aligned
            # with the trade direction and biases toward continuation)
            rsi_val   = safe_float(ind.get("rsi14") or ind.get("rsi") or 50)
            adx_val   = safe_float(ind.get("adx", 0))
            macd_h    = safe_float(ind.get("macd_hist", 0))
            macd_h_p  = safe_float(ind.get("macd_hist_prev", macd_h))
            cmf_val   = safe_float(ind.get("cmf", 0))
            mfi_val   = safe_float(ind.get("mfi", 50))
            obv_slope = safe_float(ind.get("obv_slope_10d_pct", 0))
            roc10     = safe_float(ind.get("roc10", 0))
            roc20     = safe_float(ind.get("roc20", 0))
            st_dir    = (ind.get("supertrend_dir") or "flat")
            st_dist   = safe_float(ind.get("supertrend_dist_pct", 0))
            bb_u      = safe_float(ind.get("bb_upper", 0))
            bb_l      = safe_float(ind.get("bb_lower", 0))
            bb_m      = safe_float(ind.get("bb_mid", price))
            bb_pos    = ((price - bb_l) / (bb_u - bb_l)) if bb_u > bb_l else 0.5
            atr_pct_v = safe_float(ind.get("atr_pct", 1.0))
            htf_dir   = (weekly.get("dir") if isinstance(weekly, dict) else "flat") or "flat"

            # Continuation contributions (each clamped to [-1,+1])
            def _clip(x, lo=-1.0, hi=1.0):
                return max(lo, min(hi, x))

            momentum_c   = _clip((roc10 / 5.0) * dir_sign)               # ±5% ROC = full
            macd_traj_c  = _clip(((macd_h - macd_h_p) / max(abs(macd_h) + 0.01, 0.05)) * dir_sign)
            cmf_c        = _clip((cmf_val * 5.0) * dir_sign)             # ±0.20 CMF = full
            mfi_c        = _clip(((mfi_val - 50) / 30.0) * dir_sign)
            obv_c        = _clip((obv_slope / 25.0) * dir_sign)          # ±25% slope = full
            adx_c        = _clip((adx_val - 18.0) / 20.0)                # trend persistence (no sign)
            st_c         = _clip(((1 if st_dir == "up" else -1) * dir_sign) * (1 - min(st_dist / 8.0, 1.0)))
            htf_c        = (1.0 if (signal == "BUY_CALL" and htf_dir == "up") or
                                   (signal == "BUY_PUT"  and htf_dir == "down")
                            else (-0.5 if htf_dir != "flat" else 0.0))

            # Reversion drag — extension at extremes pulls the score negative
            #   • Far past BB upper on a CALL or far below BB lower on a PUT
            #   • Stretched RSI in the trade direction
            #   • Supertrend distance > ~6% (extended)
            rev_drag = 0.0
            if signal == "BUY_CALL":
                rev_drag += max(0.0, (bb_pos - 0.85)) * 4.0          # >0.85 of BB band
                rev_drag += max(0.0, (rsi_val - 65) / 20.0)          # 65→0, 85→1
            else:
                rev_drag += max(0.0, (0.15 - bb_pos)) * 4.0
                rev_drag += max(0.0, (35 - rsi_val) / 20.0)
            rev_drag += max(0.0, (st_dist - 6.0) / 6.0)

            # Weighted blend → continuation score in [-1,+1]
            cont_raw = (
                momentum_c  * 0.22 +
                macd_traj_c * 0.14 +
                cmf_c       * 0.10 +
                mfi_c       * 0.08 +
                obv_c       * 0.10 +
                st_c        * 0.10 +
                htf_c       * 0.16 +
                adx_c       * 0.10 * (1 if abs(momentum_c) > 0 else 0)
            )
            post_forecast_score = round(_clip(cont_raw - rev_drag * 0.55), 3)

            # Bucket into a human-readable mode (the score still drives the curve)
            if post_forecast_score >= 0.30:
                post_forecast_mode = "continuation"
                post_forecast_note = (
                    f"Follow-through is strong (score {post_forecast_score:+.2f}) — "
                    f"momentum/flow/HTF aligned. Target may overshoot; consider trailing stop."
                )
            elif post_forecast_score <= -0.30:
                post_forecast_mode = "reversion"
                post_forecast_note = (
                    f"Snap-back risk (score {post_forecast_score:+.2f}) — price is stretched "
                    f"(BB pos {bb_pos:.2f}, RSI {rsi_val:.0f}). Take profits at target."
                )
            else:
                post_forecast_mode = "drift"
                post_forecast_note = (
                    f"Mixed follow-through (score {post_forecast_score:+.2f}). "
                    f"Expect a slow drift; don't hold far past target."
                )

            # Build the post-window timestamps (continue same cadence)
            post_ts: list[int] = []
            extra_bars = max(4, forecast_bars // 3)
            dt2 = datetime.fromtimestamp(last_ts, tz=timezone.utc)
            if bar_minutes >= 24 * 60:
                while len(post_ts) < extra_bars:
                    dt2 += timedelta(days=1)
                    if dt2.weekday() < 5:
                        post_ts.append(int(dt2.timestamp()))
            else:
                step = timedelta(minutes=bar_minutes)
                guard = 0
                while len(post_ts) < extra_bars and guard < extra_bars * 80:
                    dt2 = dt2 + step
                    guard += 1
                    if dt2.weekday() >= 5:
                        days_to_mon = 7 - dt2.weekday()
                        dt2 = (dt2 + timedelta(days=days_to_mon)).replace(hour=13, minute=30, second=0, microsecond=0)
                        continue
                    t2 = dt2.time()
                    if dtime(13, 30) <= t2 <= dtime(20, 0):
                        post_ts.append(int(dt2.timestamp()))
                    elif t2 > dtime(20, 0):
                        dt2 = (dt2 + timedelta(days=1)).replace(hour=13, minute=30, second=0, microsecond=0)

            # Magnitude scales with stock's own ATR AND continuation score
            atr_unit = float(atr) if atr else max(last_val * (atr_pct_v / 100.0), last_val * 0.003)
            score_mag = abs(post_forecast_score)            # 0..1
            full_move_atr = abs(last_val - entry)           # how far the trade itself moved

            # Per-symbol deterministic seed for the wave overlay so two
            # different tickers don't share the same micro-pattern.
            seed_int = sum(ord(c) for c in sym_for_post) + int(round(last_val * 100)) % 9973
            phase  = (seed_int % 360) * (np.pi / 180.0)
            freq   = 1.4 + (seed_int % 7) * 0.18            # 1.4..2.5 cycles
            wig_amp = atr_unit * (0.05 + (seed_int % 5) * 0.015)  # 0.05..0.11 ATR

            n_post = max(len(post_ts), 1)
            for j, ts in enumerate(post_ts):
                p2 = (j + 1) / n_post
                if post_forecast_mode == "continuation":
                    # Continue in trade direction, decelerating; magnitude
                    # scales with score and the stock's ATR (NOT a fixed ratio)
                    extra = atr_unit * (0.55 + score_mag * 0.85) * (1 - (1 - p2) ** 2)
                    val = last_val + dir_sign * extra
                elif post_forecast_mode == "reversion":
                    # Pull back a fraction of the trade's own move; deeper as
                    # the reversion score gets more negative
                    pullback = full_move_atr * (0.35 + score_mag * 0.45) * p2
                    val = last_val - dir_sign * pullback
                else:  # drift — gentle, score-tilted
                    bias = post_forecast_score                # signed in [-0.3,+0.3]
                    extra = atr_unit * 0.20 * p2 * (1 + bias) * dir_sign
                    pullback = full_move_atr * 0.10 * p2
                    val = last_val + extra - dir_sign * pullback
                # Per-symbol wiggle (decays so the line settles by the end)
                wiggle = wig_amp * np.sin(phase + p2 * np.pi * freq) * (1 - p2 * 0.55)
                val += wiggle
                post_forecast.append({"time": ts, "value": round(val, 2)})

        vola = ind.get("volatility_20d", 25)
        pos_size = max(1, 5 - int(vola / 15))

        # Regime-aware Kelly criterion sizing (uses back-test stats per vol regime)
        kelly = compute_position_size(
            signal=signal, confidence=conf, entry=entry, target=target, stop=stop,
            atr_pct=atr_pct_now,
        )

        # Per-stock historical track record — keeps confidence calibrated to reality.
        # Discovered in back-test that the model's hit rate varies WIDELY by symbol
        # (META 80%, MSFT 70%, NVDA 12.5%) and that high-confidence trades aren't
        # any more accurate than low-confidence ones. Show users the truth.
        track_record = get_track_record(ind.get("_symbol", ""))

        # ── REAL TARGET-HIT PROBABILITY ─────────────────────────────────
        # Replace the old "average of agent votes" confidence with the actual
        # probability that price will touch the target inside the forecast
        # window. Uses volatility math (Brownian first-passage) + directional
        # alignment of SuperTrend, EMA, MACD, RSI, BB, Volume, OBV, ADX,
        # Williams %R, Ichimoku, VWAP, Pivot bias, Stochastic, multi-TF trend
        # + per-stock historical hit-rate calibration.
        hit = compute_target_hit_probability(
            signal=signal, price=price, target=target, atr=atr, ind=ind,
            days=max(1, target_hit_bars * bar_minutes // (24 * 60)),
            bars=target_hit_bars,
            bar_minutes=bar_minutes,
            hist_hit_rate=track_record["hit_rate"] if track_record else None,
        )

        # Blend the volatility-aware target-hit probability (objective —
        # Brownian first-passage on ATR) with the multiplier-adjusted vote
        # confidence (HTF tilt + conviction-dominance + regime + fundamentals
        # + macro all bake in here). Pure hit-prob saturates at 95% on every
        # decent swing setup; pure vote-conf ignores volatility. 60/40 blend
        # gives an honest, well-spread number that responds to all gates.
        vote_consensus = round(conf, 1)
        blended = 0.60 * float(hit["prob_pct"]) + 0.40 * float(conf)
        # Honest ceiling — the real swing hit-rate from back-testing is
        # ~73-87%, so capping at 90% prevents systemic overconfidence.
        conf = round(max(5.0, min(90.0, blended)), 1)

        # If the model has historically been WORSE than coin-flip on this stock,
        # cap reported confidence — refusing to overstate conviction is honest.
        if track_record and track_record["rating"] in ("weak", "poor") and signal != "HOLD":
            conf = min(conf, 55.0)

        # Get Fear & Greed from cache if available
        fg_score = FearGreedAgent._cache.get("score", 50) if FearGreedAgent._cache else 50
        fg_label = FearGreedAgent._cache.get("label", "Unknown") if FearGreedAgent._cache else "Unknown"

        return {
            "signal": signal,
            "confidence": round(conf, 1),
            "target_hit_prob": round(conf, 1),         # alias for clarity in UI
            "target_hit_base_pct": hit["base_pct"],    # vol-only baseline
            "target_hit_alignment": hit["alignment"],  # -1..+1 indicator agreement
            "target_hit_boost_pct": hit["alignment_pct_boost"],
            "target_hit_breakdown": hit["breakdown"],  # per-indicator contribution
            "target_hit_method": hit["method"],
            "target_hit_days": hit["days"],
            "vote_consensus_pct": vote_consensus,      # the old number, for transparency
            "entry_price": round(entry, 2),
            "stop_loss": round(stop, 2),
            "target_price": round(target, 2),
            "agreed_agents": agreed,
            "disagreed_agents": disagreed,
            "vote_tally": {"BUY_CALL": call_count, "BUY_PUT": put_count, "HOLD": hold_count},
            "position_size_pct": pos_size,
            "kelly": kelly,
            "track_record": track_record,
            "judge_reason": (
                f"{call_count}/{total_analysts} CALL, {put_count}/{total_analysts} PUT — " +
                (f"🛑 VETO: {veto_reason}" if veto_reason
                 else (f"🛑 NO BACKING: {evidence_reason}" if evidence_reason
                       else ("✅ CONSENSUS" if signal != "HOLD"
                             else f"⏳ Need {threshold}/{total_analysts}")))
            ),
            "horizon": {
                "key": horizon.get("key", DEFAULT_HORIZON),
                "label": horizon.get("label", ""),
                "threshold": threshold,
                "bar_minutes": bar_minutes,
                "forecast_bars": forecast_bars,
                "expiry_pref": horizon.get("expiry_pref", ""),
            },
            "evidence_reason": evidence_reason,
            "evidence_pillars": evidence_pillars or None,
            "macro_context": {
                "adx": round(adx, 1),
                "weekly_trend": weekly,
                "spy_trend": spy,
                "regime": regime,
                "macro_basket": macro,
                "sector_rotation": ind.get("sector_rotation"),
                "fundamentals": fund,
                "short_squeeze": squeeze,
                "earnings": ind.get("earnings"),
                "discovered_strategies": disc,
            },
            "action": opts["action"],
            "strike_hint": opts["strike_hint"],
            # NEW: numeric strike + premium/breakeven/delta/moneyness for the
            # richer Options card in the UI. Old `strike_hint` text is kept
            # for any older client that's still parsing it.
            "strike": opts.get("strike", 0.0),
            "strike_moneyness": opts.get("strike_moneyness", ""),
            "strike_premium_est": opts.get("strike_premium_est", 0.0),
            "strike_delta_est": opts.get("strike_delta_est", 0.0),
            "strike_breakeven": opts.get("strike_breakeven", 0.0),
            "strike_primary_expiry": opts.get("strike_primary_expiry", ""),
            "strike_primary_dte": opts.get("strike_primary_dte", 0),
            "expiry_hint": opts["expiry_hint"],
            "expiry_weekly": opts.get("expiry_weekly", ""),
            "expiry_biweekly": opts.get("expiry_biweekly", ""),
            "expiry_monthly": opts.get("expiry_monthly", ""),
            "entry_trigger": opts["entry_trigger"],
            "risk_note": opts["risk_note"],
            "forecast_line": forecast,
            "post_forecast_line": post_forecast,
            "post_forecast_mode": post_forecast_mode,
            "post_forecast_note": post_forecast_note,
            "post_forecast_score": post_forecast_score,
            "fear_greed_score": fg_score,
            "fear_greed_label": fg_label,
        }
