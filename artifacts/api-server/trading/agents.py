            n = len(closes)
            if n < 10:
                return _hold(self.name, self.emoji, "Not enough data")

            price = closes[-1]
            signals, reasons = [], []

            roc5 = (closes[-1] - closes[-5]) / closes[-5] * 100 if n >= 5 and closes[-5] > 0 else 0
            roc10 = (closes[-1] - closes[-10]) / closes[-10] * 100 if n >= 10 and closes[-10] > 0 else 0

