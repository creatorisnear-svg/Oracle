class PoliticalAgent:
    name = "Political Agent"
    emoji = "🏛️"
    method = "Google News RSS scraper for Trump + tariff + Fed + macro keywords — market impact scoring"

    # NOTE: All keywords use multi-word phrases to avoid false matches.
    # E.g. bare "china" matched both "china tariff" (bearish) and "china deal"
    # (bullish), netting to noise. Bigrams disambiguate context.
    MARKET_BULLISH = [
        "tax cut", "deregulation", "stimulus", "trade deal", "trade agreement",
        "rate cut", "rate hold", "fed pause", "fed eases", "pro-business",
        "infrastructure bill", "bill signed", "bill passed", "economic boom",
        "economic recovery", "strong economy", "jobs added", "beats expectations",
        "ceasefire", "peace deal", "tariff removed", "tariff exemption",
        "tariff lifted", "china deal", "china agreement", "rally extends",
        "market gains", "earnings beat",
    ]
    MARKET_BEARISH = [
        "trade war", "new tariff", "additional tariff", "tariff hike",
        "tariffs raised", "china tariff", "china sanction", "china retaliation",
        "sanctions imposed", "export ban", "escalates tensions", "retaliate",
        "recession risk", "inflation surge", "rate hike", "hawkish fed",
        "fed tightening", "debt ceiling", "government shutdown", "us default",
        "war breaks out", "armed conflict", "geopolitical tension",
        "doj investigation", "indicted", "impeachment", "financial crisis",
        "market crash", "stocks plunge", "mass layoff", "bankruptcy filing",
        "earnings miss", "disappoints expectations", "policy uncertainty",
    ]

    # Tokens that flip the meaning of a nearby keyword. Scanned within a
    # small window before a matched phrase, plus a forward window for
    # post-modifiers ("averted", "called off", "ruled out", "denied").
    NEGATIONS = ("no ", "not ", "never ", "without ", "avoids ", "averted ",
                 "no longer ", "ruled out ", "denies ", "rejects ")
    POST_NEGATIONS = (" averted", " avoided", " called off", " halted",
                      " ruled out", " denied", " walked back", " reversed")

    _news_cache: list = []
    _cache_ts: float = 0
    CACHE_TTL = 120  # 2 minutes

    def _fetch_political_news(self) -> list:
        if time.time() - PoliticalAgent._cache_ts < self.CACHE_TTL and PoliticalAgent._news_cache:
            return PoliticalAgent._news_cache

        queries = [
            "trump tariff stock market economy",
            "federal reserve interest rate economy",
            "US economy recession inflation",
        ]
        all_news = []
        for q in queries[:2]:
            try:
                q_enc = q.replace(" ", "+")
                url = f"https://news.google.com/rss/search?q={q_enc}&hl=en-US&gl=US&ceid=US:en"
                req = urllib.request.Request(url, headers={
                    "User-Agent": "Mozilla/5.0 (compatible; TradeSignalAI/1.0)"
                })
                with urllib.request.urlopen(req, timeout=6) as resp:
                    content = resp.read()
                root = ET.fromstring(content)
                for item in root.findall(".//item")[:6]:
                    title = html_lib.unescape(item.findtext("title", ""))
                    link = item.findtext("link", "")
                    pub = item.findtext("pubDate", "")
                    source_el = item.find("{http://purl.org/dc/elements/1.1/}creator")
                    source = source_el.text if source_el is not None else "Google News"
                    all_news.append({
                        "title": title,
                        "url": link,
                        "source": source,
                        "published_at": pub,
                        "category": "political",
                    })
            except Exception as e:
                logger.debug(f"Google News fetch failed: {e}")

        PoliticalAgent._news_cache = all_news
        PoliticalAgent._cache_ts = time.time()
        return all_news

    # Cache compiled patterns once per class (not per call).
    _BULL_RX: list = []
    _BEAR_RX: list = []

    @classmethod
    def _patterns(cls) -> tuple[list, list]:
        if not cls._BULL_RX:
            cls._BULL_RX = [re.compile(rf"\b{re.escape(w)}\b") for w in cls.MARKET_BULLISH]
            cls._BEAR_RX = [re.compile(rf"\b{re.escape(w)}\b") for w in cls.MARKET_BEARISH]
        return cls._BULL_RX, cls._BEAR_RX

    def _negated(self, text: str, idx: int, length: int) -> bool:
        """True if the keyword spanning [idx, idx+length) is negated.

        Scans both a backward window (~25 chars before) for "no/not/never/..."
        prefixes AND a forward window (~22 chars after the phrase ends) for
        post-modifiers like "averted", "called off", "walked back".
        """
        before = text[max(0, idx - 25):idx]
        after = text[idx + length: idx + length + 22]
        if any(neg in before for neg in self.NEGATIONS):
            return True
        return any(post in after for post in self.POST_NEGATIONS)

    def _count_phrases(self, text: str, regexes: list) -> int:
        """Count phrase hits, skipping any whose nearby context negates them.
        `re.finditer` yields non-overlapping word-bounded matches, so 'tariff'
        no longer matches inside 'tariffs raised' twice and 'cut' no longer
        matches 'executive'.
        """
        n = 0
        for rx in regexes:
            for m in rx.finditer(text):
                if not self._negated(text, m.start(), m.end() - m.start()):
                    n += 1
        return n

    def analyze(self, df, ind):
        try:
            news = self._fetch_political_news()
            # Also check Yahoo Finance news for political keywords
            yahoo_news = ind.get("_news", [])
            all_news = news + yahoo_news

            if not all_news:
                return _hold(self.name, self.emoji, "No political news available")

            bull = bear = 0
            top_headlines = []
            for item in all_news[:15]:
                title = (item.get("title", "") + " " + item.get("summary", "")).lower()
                bull_rx, bear_rx = self._patterns()
                item_bull = self._count_phrases(title, bull_rx)
                item_bear = self._count_phrases(title, bear_rx)
                bull += item_bull
                bear += item_bear
                if item_bull > 0 or item_bear > 0:
                    top_headlines.append(item.get("title", "")[:60])

            total = bull + bear
            if total == 0:
                return _hold(self.name, self.emoji, "Politically neutral news cycle")

            ratio = bull / total
            conf = 54 + abs(bull - bear) / max(total, 1) * 28
            headline_str = top_headlines[0][:50] if top_headlines else ""

            if ratio > 0.62:
                return _vote(self.name, self.emoji, "BUY_CALL", conf,
                             f"Pro-market news {bull}↑/{bear}↓ | {headline_str}")
            elif ratio < 0.38:
                return _vote(self.name, self.emoji, "BUY_PUT", conf,
                             f"Anti-market news {bear}↓/{bull}↑ | {headline_str}")
            return _hold(self.name, self.emoji, f"Mixed macro/political signals {bull}↑/{bear}↓")
        except Exception as e:
            return _hold(self.name, self.emoji, f"Political data unavailable: {e}")


