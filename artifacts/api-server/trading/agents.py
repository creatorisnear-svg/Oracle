class PoliticalAgent:
    name = "Political Agent"
    emoji = "🏛️"
    method = "Google News RSS scraper for Trump + tariff + Fed + macro keywords — market impact scoring"

    # NOTE: All keywords use multi-word phrases to avoid false matches.
    # E.g. bare "china" matched both "china tariff" (bearish) and "china deal"
    # (bullish), netting to noise. Bigrams disambiguate context.
    MARKET_BULLISH = [
        "tax cut", "deregulation", "stimulus", "trade deal", "trade agreement",
        "rate cut", "rate hold", "fed pause", "fed eases", "pro-business",
        "infrastructure bill", "bill signed", "bill passed", "economic boom",
        "economic recovery", "strong economy", "jobs added", "beats expectations",
        "ceasefire", "peace deal", "tariff removed", "tariff exemption",
        "tariff lifted", "china deal", "china agreement", "rally extends",
        "market gains", "earnings beat",
    ]
    MARKET_BEARISH = [
        "trade war", "new tariff", "additional tariff", "tariff hike",
        "tariffs raised", "china tariff", "china sanction", "china retaliation",
        "sanctions imposed", "export ban", "escalates tensions", "retaliate",
        "recession risk", "inflation surge", "rate hike", "hawkish fed",
        "fed tightening", "debt ceiling", "government shutdown", "us default",
        "war breaks out", "armed conflict", "geopolitical tension",
        "doj investigation", "indicted", "impeachment", "financial crisis",
        "market crash", "stocks plunge", "mass layoff", "bankruptcy filing",
        "earnings miss", "disappoints expectations", "policy uncertainty",
    ]

    # Tokens that flip the meaning of a nearby keyword. Scanned within a
    # small window before a matched phrase, plus a forward window for
    # post-modifiers ("averted", "called off", "ruled out", "denied").
    NEGATIONS = ("no ", "not ", "never ", "without ", "avoids ", "averted ",
                 "no longer ", "ruled out ", "denies ", "rejects ")
    POST_NEGATIONS = (" averted", " avoided", " called off", " halted",
                      " ruled out", " denied", " walked back", " reversed")

    _news_cache: list = []
    _cache_ts: float = 0
    CACHE_TTL = 120  # 2 minutes

    def _fetch_political_news(self) -> list:
        if time.time() - PoliticalAgent._cache_ts < self.CACHE_TTL and PoliticalAgent._news_cache:
            return PoliticalAgent._news_cache

        queries = [
            "trump tariff stock market economy",
            "federal reserve interest rate economy",
            "US economy recession inflation",
        ]
        all_news = []
        for q in queries[:2]:
            try:
                q_enc = q.replace(" ", "+")
                url = f"https://news.google.com/rss/search?q={q_enc}&hl=en-US&gl=US&ceid=US:en"
                req = urllib.request.Request(url, headers={
                    "User-Agent": "Mozilla/5.0 (compatible; TradeSignalAI/1.0)"
                })
                with urllib.request.urlopen(req, timeout=6) as resp:
                    content = resp.read()
                root = ET.fromstring(content)
                for item in root.findall(".//item")[:6]:
                    title = html_lib.unescape(item.findtext("title", ""))
                    link = item.findtext("link", "")
                    pub = item.findtext("pubDate", "")
                    source_el = item.find("{http://purl.org/dc/elements/1.1/}creator")
                    source = source_el.text if source_el is not None else "Google News"
                    all_news.append({
                        "title": title,
                        "url": link,
                        "source": source,
                        "published_at": pub,
                        "category": "political",
                    })
            except Exception as e:
                logger.debug(f"Google News fetch failed: {e}")

        PoliticalAgent._news_cache = all_news
        PoliticalAgent._cache_ts = time.time()
        return all_news

    # Cache compiled patterns once per class (not per call).
    _BULL_RX: list = []
    _BEAR_RX: list = []

    @classmethod
    def _patterns(cls) -> tuple[list, list]:
        if not cls._BULL_RX:
            cls._BULL_RX = [re.compile(rf"\b{re.escape(w)}\b") for w in cls.MARKET_BULLISH]
            cls._BEAR_RX = [re.compile(rf"\b{re.escape(w)}\b") for w in cls.MARKET_BEARISH]
        return cls._BULL_RX, cls._BEAR_RX

    def _negated(self, text: str, idx: int, length: int) -> bool:
        """True if the keyword spanning [idx, idx+length) is negated.

        Scans both a backward window (~25 chars before) for "no/not/never/..."
        prefixes AND a forward window (~22 chars after the phrase ends) for
        post-modifiers like "averted", "called off", "walked back".
        """
        before = text[max(0, idx - 25):idx]
        after = text[idx + length: idx + length + 22]
        if any(neg in before for neg in self.NEGATIONS):
            return True
        return any(post in after for post in self.POST_NEGATIONS)

    def _count_phrases(self, text: str, regexes: list) -> int:
        """Count phrase hits, skipping any whose nearby context negates them.
        `re.finditer` yields non-overlapping word-bounded matches, so 'tariff'
        no longer matches inside 'tariffs raised' twice and 'cut' no longer
        matches 'executive'.
        """
        n = 0
        for rx in regexes:
            for m in rx.finditer(text):
                if not self._negated(text, m.start(), m.end() - m.start()):
                    n += 1
        return n

    def analyze(self, df, ind):
        try:
            news = self._fetch_political_news()
            # Also check Yahoo Finance news for political keywords
            yahoo_news = ind.get("_news", [])
            all_news = news + yahoo_news

            if not all_news:
                return _hold(self.name, self.emoji, "No political news available")

            bull = bear = 0
            top_headlines = []
            for item in all_news[:15]:
                title = (item.get("title", "") + " " + item.get("summary", "")).lower()
                bull_rx, bear_rx = self._patterns()
                item_bull = self._count_phrases(title, bull_rx)
                item_bear = self._count_phrases(title, bear_rx)
                bull += item_bull
                bear += item_bear
                if item_bull > 0 or item_bear > 0:
                    top_headlines.append(item.get("title", "")[:60])

            total = bull + bear
            if total == 0:
                return _hold(self.name, self.emoji, "Politically neutral news cycle")

            ratio = bull / total
            conf = 54 + abs(bull - bear) / max(total, 1) * 28
            headline_str = top_headlines[0][:50] if top_headlines else ""

            if ratio > 0.62:
                return _vote(self.name, self.emoji, "BUY_CALL", conf,
                             f"Pro-market news {bull}↑/{bear}↓ | {headline_str}")
            elif ratio < 0.38:
                return _vote(self.name, self.emoji, "BUY_PUT", conf,
                             f"Anti-market news {bear}↓/{bull}↑ | {headline_str}")
            return _hold(self.name, self.emoji, f"Mixed macro/political signals {bull}↑/{bear}↓")
        except Exception as e:
            return _hold(self.name, self.emoji, f"Political data unavailable: {e}")


# ─────────────────────────────────────────────────────────────────────────────
# TARGET-HIT PROBABILITY  (replaces the old "agent vote average" confidence)
# ─────────────────────────────────────────────────────────────────────────────
def compute_target_hit_probability(
    *,
    signal: str,
    price: float,
    target: float,
    atr: float,
    ind: dict,
    days: int = 7,
    bars: int | None = None,
    bar_minutes: int = 24 * 60,
    hist_hit_rate: float | None = None,
) -> dict:
    """
    Estimate the probability that price will TOUCH `target` within `days`
    trading days, combining:

      A. Volatility-grounded base rate (Brownian first-passage formula
         using ATR as the daily vol proxy).  Far targets vs daily noise
         → low base; close targets → high base.

      B. Directional alignment of the full indicator suite —
         SuperTrend, EMA 9/21, MACD, RSI, Bollinger position,
         Volume (rel + up/dn ratio), OBV slope, ADX trend, Williams %R,
         Ichimoku, VWAP, Pivot bias, Stochastic, multi-TF trend.
         Each indicator votes for or against the target direction;
         the weighted consensus boosts (or suppresses) the base rate.

      C. Per-stock historical hit-rate calibration — blends in the
         model's actual track record on this specific symbol.

    Returns: { prob_pct, base_pct, alignment, alignment_pct_boost,
               breakdown[], method, days }
    """
    # HOLD or degenerate inputs → meaningless
    if signal == "HOLD" or price <= 0 or target == price or atr <= 0:
        return {
            "prob_pct": 50.0,
            "base_pct": 50.0,
            "alignment": 0.0,
            "alignment_pct_boost": 0.0,
            "breakdown": [],
            "method": "neutral (no directional signal)",
            "days": days,
        }

    # ── A. Volatility-based first-passage probability ───────────────
    # 1 ATR ≈ 1 bar's expected price range, so σ_per_bar ≈ atr / price.
    # Probability of touching a barrier D away within N bars under
    # zero-drift Brownian motion: 2·(1 − Φ(D / (σ·√N))).
    # When `bars` is given (intraday/swing) we use bar-based math so the
    # window is correct for ANY interval (5m, 15m, 1h, 1d).
    n_bars = int(bars) if bars and bars > 0 else int(days)
    sigma_per_bar = atr / price
    distance_pct = abs(target - price) / price
    z = distance_pct / (sigma_per_bar * math.sqrt(max(n_bars, 1)))
    p_base = 2.0 * (1.0 - norm.cdf(z))
    p_base = max(0.05, min(0.95, p_base))

    # ── B. Directional alignment score in [-1, +1] ──────────────────
    is_call = (signal == "BUY_CALL")
    breakdown: list[dict] = []
    total_signed = 0.0
    total_weight = 0.0

    def _add(name: str, weight: float, bull_cond: bool, bear_cond: bool, detail: str = ""):
        nonlocal total_signed, total_weight
        if bull_cond:
            contrib = weight if is_call else -weight
            arrow = "↑"
        elif bear_cond:
            contrib = -weight if is_call else weight
            arrow = "↓"
        else:
            contrib = 0.0
            arrow = "·"
        total_signed += contrib
        total_weight += weight
        breakdown.append({
            "indicator": name,
            "direction": arrow,
            "weight": weight,
            "contrib": round(contrib, 2),
            "detail": detail,
            "supports_target": contrib > 0,
        })

    # SuperTrend (highest weight — primary trend follower)
    st_dir = ind.get("supertrend_dir", "")
    _add("SuperTrend", 2.0, st_dir == "up", st_dir == "down", f"{st_dir or 'n/a'}")

    # Multi-timeframe composite trend
    trend = float(ind.get("trend_score") or 0)
    _add("Multi-TF Trend", 1.5, trend > 0.3, trend < -0.3, f"score {trend:+.2f}")

    # Volume confirmation (relative volume + up/down vol balance)
    rel_vol = float(ind.get("rel_volume") or 1.0)
    ud_ratio = float(ind.get("up_dn_vol_ratio") or 1.0)
    _add("Volume", 1.2,
         rel_vol > 1.3 and ud_ratio > 1.1,
         rel_vol > 1.3 and ud_ratio < 0.9,
         f"{rel_vol:.2f}x avg, U/D {ud_ratio:.2f}")

    # EMA 9/21 crossover
    ema9 = float(ind.get("ema9") or 0)
    ema21 = float(ind.get("ema21") or 0)
    _add("EMA 9/21", 1.0, ema9 > ema21, ema9 < ema21,
         f"{ema9:.2f} vs {ema21:.2f}")

    # MACD direction
    macd = float(ind.get("macd") or 0)
    macd_sig = float(ind.get("macd_signal") or 0)
    _add("MACD", 1.0, macd > macd_sig, macd < macd_sig,
         f"{macd:+.3f} vs {macd_sig:+.3f}")

    # RSI momentum (50–70 bullish, 30–50 bearish; outside = exhaustion → neutral)
    rsi = float(ind.get("rsi14") or 50)
    _add("RSI", 1.0, 50 < rsi < 70, 30 < rsi < 50, f"{rsi:.1f}")

    # OBV slope (institutional accumulation)
    obv_slope = float(ind.get("obv_slope_10d_pct") or 0)
    _add("OBV Trend", 1.0, obv_slope > 1.0, obv_slope < -1.0,
         f"{obv_slope:+.1f}% / 10d")

    # ADX trend strength (only counts when DI direction is established)
    adx = float(ind.get("adx") or 0)
    plus_di = float(ind.get("plus_di") or 0)
    minus_di = float(ind.get("minus_di") or 0)
    _add("ADX Trend", 1.0,
         adx >= 25 and plus_di > minus_di,
         adx >= 25 and minus_di > plus_di,
         f"ADX {adx:.0f}, +DI {plus_di:.0f} / -DI {minus_di:.0f}")

    # Ichimoku cloud signal
    ichi = str(ind.get("ichimoku_signal") or "neutral").lower()
    _add("Ichimoku", 1.0, "bull" in ichi, "bear" in ichi, ichi)

    # Bollinger Band position (z within band)
    bb_u = float(ind.get("bb_upper") or price * 1.05)
    bb_l = float(ind.get("bb_lower") or price * 0.95)
    bb_m = float(ind.get("bb_mid") or price)
    bb_w = bb_u - bb_l
    bb_z = ((price - bb_m) / (bb_w / 2)) if bb_w > 0 else 0.0
    _add("Bollinger Pos", 0.8, 0 < bb_z < 0.7, -0.7 < bb_z < 0,
         f"z {bb_z:+.2f}")

    # VWAP relationship
    vwap_pct = float(ind.get("price_vs_vwap_pct") or 0)
    _add("VWAP", 0.8, vwap_pct > 0.2, vwap_pct < -0.2, f"{vwap_pct:+.2f}%")

    # Pivot bias
    pb = str(ind.get("pivot_bias") or "neutral")
    _add("Pivots", 0.8, "bull" in pb, "bear" in pb, pb)

    # Stochastic
    stoch = float(ind.get("stoch_k") or 50)
    _add("Stochastic", 0.5, 50 < stoch < 80, 20 < stoch < 50, f"K {stoch:.0f}")

    # Williams %R (-50..-20 = bullish zone, -80..-50 = bearish)
    wr = float(ind.get("williams_r") or -50)
    _add("Williams %R", 0.5, -50 < wr < -20, -80 < wr < -50, f"{wr:.0f}")

    alignment = (total_signed / total_weight) if total_weight > 0 else 0.0
    alignment = max(-1.0, min(1.0, alignment))

    # ── C. Combine: aligned signals can boost up to +40%, opposing −40%
    multiplier = 1.0 + 0.4 * alignment
    p_signal = p_base * multiplier

    # ── D. Per-stock historical calibration (blend 30% if known) ────
    if hist_hit_rate is not None and 0 < hist_hit_rate <= 100:
        hist_p = hist_hit_rate / 100.0
        p_final = 0.7 * p_signal + 0.3 * hist_p
        method = (f"vol-base {p_base*100:.0f}% × align {multiplier:.2f}x "
                  f"→ blend hist {hist_hit_rate:.0f}%")
    else:
        p_final = p_signal
        method = f"vol-base {p_base*100:.0f}% × align {multiplier:.2f}x"

    p_final = max(5.0, min(95.0, p_final * 100))

    # Sort breakdown by absolute contribution so the most influential
    # indicators show first in the UI.
    breakdown.sort(key=lambda r: abs(r["contrib"]), reverse=True)

    return {
        "prob_pct": round(p_final, 1),
        "base_pct": round(p_base * 100, 1),
        "alignment": round(alignment, 3),
        "alignment_pct_boost": round((multiplier - 1.0) * 100, 1),
        "breakdown": breakdown,
        "method": method,
        "days": days,
        "bars": n_bars,
        "bar_minutes": bar_minutes,
    }


