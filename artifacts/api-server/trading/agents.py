class OptionsFlowAgent:
    name = "Options Flow Agent"
    emoji = "🎯"
    method = "Put/Call OI ratio + Put/Call volume ratio (real options chain from Yahoo Finance)"

    def analyze(self, df, ind):
        try:
            import yfinance as yf
            symbol = ind.get("_symbol", "")
            if not symbol:
                return _hold(self.name, self.emoji, "No symbol")
            ticker = yf.Ticker(symbol)
            dates = ticker.options
            if not dates:
                return _hold(self.name, self.emoji, "No options chain")

            chain0 = ticker.option_chain(dates[0])
            calls = chain0.calls
            puts = chain0.puts
            total_call_oi = safe_float(calls["openInterest"].sum()) if "openInterest" in calls.columns else 0
            total_put_oi = safe_float(puts["openInterest"].sum()) if "openInterest" in puts.columns else 0
            total_call_vol = safe_float(calls["volume"].sum()) if "volume" in calls.columns else 0
            total_put_vol = safe_float(puts["volume"].sum()) if "volume" in puts.columns else 0

            pc_oi = total_put_oi / total_call_oi if total_call_oi > 0 else 1
            pc_vol = total_put_vol / total_call_vol if total_call_vol > 0 else 1
            total_vol = total_call_vol + total_put_vol
            reasons = [f"P/C OI:{pc_oi:.2f}", f"P/C Vol:{pc_vol:.2f}"]

            # ── IV-vs-realized-vol gate (IVR proxy) ─────────────────────
            # True 52-wk IVR needs an IV history database (paid). A clean
            # free proxy: compare current at-the-money implied vol to 20-day
            # REALIZED volatility. When IV >> RV, options are priced for a
            # bigger move than the stock has been making — long calls/puts
            # have a structural disadvantage (vega bleed + IV-crush risk).
            # When IV < RV, options are cheap relative to actual movement
            # (favourable for long premium).
            iv_pct = None
            iv_rv_ratio = None
            try:
                price_now = float(ind.get("price") or 0)
                if price_now > 0 and "strike" in calls.columns and "impliedVolatility" in calls.columns:
                    # ATM = strikes within ±7% of spot (median is robust to outlier wings)
                    near_atm = calls[(calls["strike"] >= price_now * 0.93) &
                                     (calls["strike"] <= price_now * 1.07)]
                    if len(near_atm) >= 3:
                        iv_med = float(near_atm["impliedVolatility"].median())
                        iv_pct = round(iv_med * 100, 1)  # 0.42 → 42.0
                        # Compute realized vol from DAILY bars to match yfinance IV
                        # (which is annualized off daily). Reusing ind["volatility_20d"]
                        # was wrong: for swing/intraday horizons that field is built
                        # from hourly/5-minute bars but still annualised with
                        # sqrt(252), under-reporting RV by ~2.5×–8.8× and making
                        # the IV/RV ratio fire "expensive" on every signal.
                        rv = 0.0
                        try:
                            daily = ticker.history(period="2mo", interval="1d", auto_adjust=False)
                            if daily is not None and len(daily) >= 21:
                                closes_d = daily["Close"].dropna().values[-21:]
                                if len(closes_d) >= 21:
                                    rets = np.diff(closes_d) / closes_d[:-1]
                                    rv = float(np.std(rets) * np.sqrt(252) * 100)
                        except Exception:
                            rv = float(ind.get("volatility_20d") or 0)
                        if rv > 0 and iv_pct > 0:
                            iv_rv_ratio = round(iv_pct / rv, 2)
                            reasons.append(f"IV/RV:{iv_rv_ratio:.2f} (IV {iv_pct:.0f}% vs RV {rv:.0f}%)")
            except Exception as _e:
                logger.debug(f"IV/RV calc failed: {_e}")

            # ── Evidence-quality gate #1: minimum option volume ─────────
            # Thinly-traded chains produce noisy ratios — a single big trade
            # can flip the P/C ratio. Require at least 1,000 contracts of
            # combined volume before trusting the signal at all.
            if total_vol < 1000:
                return _hold(
                    self.name, self.emoji,
                    f"Thin options volume ({int(total_vol)} contracts) — ratio unreliable",
                )

            # ── Evidence-quality gate #2: tape confirmation ─────────────
            # Options flow alone is contrarian-prone: heavy put buying
            # often happens AS hedging into rallies, not because the stock
            # is about to fall. Confirm with the actual price tape:
            #   bullish tape  = supertrend up  AND ema9 > ema21
            #   bearish tape  = supertrend dn  AND ema9 < ema21
            #   mixed tape    = anything else
            st_dir = ind.get("supertrend_dir", "up")
            ema9 = ind.get("ema9", 0)
            ema21 = ind.get("ema21", 0)
            tape_bull = (st_dir == "up") and (ema9 > ema21)
            tape_bear = (st_dir == "down") and (ema9 < ema21)

            # Decide raw direction from option flow
            if pc_vol < 0.5:    raw_dir, raw_conf, label = "BUY_CALL", 82, "Heavy call flow"
            elif pc_vol < 0.7:  raw_dir, raw_conf, label = "BUY_CALL", 70, "Call dominance"
            elif pc_vol > 2.0:  raw_dir, raw_conf, label = "BUY_PUT",  82, "Heavy put flow"
            elif pc_vol > 1.4:  raw_dir, raw_conf, label = "BUY_PUT",  70, "Put dominance"
            elif pc_oi  < 0.7:  raw_dir, raw_conf, label = "BUY_CALL", 63, "Call OI dominance"
            elif pc_oi  > 1.3:  raw_dir, raw_conf, label = "BUY_PUT",  63, "Put OI dominance"
            else:
                return _hold(self.name, self.emoji, f"Neutral flow — {' '.join(reasons)}")

            # Tape contradicts flow → HOLD ("nothing backing it up")
            if raw_dir == "BUY_CALL" and tape_bear:
                return _hold(
                    self.name, self.emoji,
                    f"{label} but tape bearish (ST down, EMA9<EMA21) — no confirmation",
                )
            if raw_dir == "BUY_PUT" and tape_bull:
                return _hold(
                    self.name, self.emoji,
                    f"{label} but tape bullish (ST up, EMA9>EMA21) — no confirmation",
                )

            # Tape mixed → trim confidence; tape aligned → keep it
            tape_aligned = (raw_dir == "BUY_CALL" and tape_bull) or (raw_dir == "BUY_PUT" and tape_bear)
            if not tape_aligned:
                raw_conf = max(55.0, raw_conf * 0.75)
                label += " (mixed tape)"

            # ── IV/RV adjustment ────────────────────────────────────────
            # Long options pay vega — when IV is rich vs realized vol the
            # premium is structurally too expensive. Trim confidence so
            # the Judge thinks twice. When IV is cheap, give a small boost.
            if iv_rv_ratio is not None:
                if iv_rv_ratio >= 1.6:
                    raw_conf *= 0.80
                    label += " (IV expensive)"
                elif iv_rv_ratio >= 1.3:
                    raw_conf *= 0.90
                elif iv_rv_ratio <= 0.8:
                    raw_conf = min(95.0, raw_conf * 1.05)
                    label += " (IV cheap)"

            vote = _vote(self.name, self.emoji, raw_dir, raw_conf, f"{label} — {' '.join(reasons)}")
            # Surface IV stats for the Judge / UI
            if iv_pct is not None:
                vote["iv_atm_pct"] = iv_pct
            if iv_rv_ratio is not None:
                vote["iv_rv_ratio"] = iv_rv_ratio
            return vote
        except Exception as e:
            return _hold(self.name, self.emoji, f"Options unavailable: {e}")


