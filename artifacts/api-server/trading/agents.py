def compute_htf_trend(htf_df) -> dict:
    """Higher-timeframe trend filter.

    Pro traders only fire short-term setups in the direction of the bigger
    picture. We compute EMA20/EMA50 on the next-higher timeframe and return:

      * direction:  +1 = up-trend, -1 = down-trend, 0 = chop / unknown
      * strength :  0..1 — how cleanly the trend is aligned (slope steepness)
      * label    :  human-readable label for the UI
    """
    try:
        import numpy as _np
        if htf_df is None or len(htf_df) < 55:
            return {"direction": 0, "strength": 0.0, "label": "unknown"}
        close = htf_df["Close"].values.astype(float)

        def _ema(arr, span):
            k = 2.0 / (span + 1.0)
            out = _np.empty_like(arr)
            out[0] = arr[0]
            for i in range(1, len(arr)):
                out[i] = arr[i] * k + out[i - 1] * (1 - k)
            return out

        ema20 = _ema(close, 20)
        ema50 = _ema(close, 50)
        last_close = float(close[-1])
        last_e20 = float(ema20[-1])
        last_e50 = float(ema50[-1])
        # slope of EMA50 over last 10 bars, normalised to price
        slope = (float(ema50[-1]) - float(ema50[-10])) / max(last_close, 1e-6)

        up = (last_e20 > last_e50) and (last_close > last_e50)
        down = (last_e20 < last_e50) and (last_close < last_e50)
        if up:
            direction = 1
            label = "up-trend"
        elif down:
            direction = -1
            label = "down-trend"
        else:
            direction = 0
            label = "chop"
        strength = float(min(1.0, abs(slope) * 200.0))   # 0.5% slope ≈ 1.0
        return {"direction": direction, "strength": round(strength, 3), "label": label}
    except Exception:
        return {"direction": 0, "strength": 0.0, "label": "unknown"}


def get_track_record(symbol: str) -> dict | None:
    """Return the model's historical hit-rate on this stock, or None if not tracked."""
    if not symbol or not _TRACK_RECORD:
        return None
    rec = (_TRACK_RECORD.get("per_stock") or {}).get(symbol.upper())
    if not rec or rec.get("hit_rate") is None or rec.get("signals", 0) < 3:
        return None
    hr = rec["hit_rate"]
    if hr >= 65:
        rating = "strong"; note = f"Model has been right {hr}% of the time on {symbol} (n={rec['signals']})."
    elif hr >= 55:
        rating = "good"; note = f"Model historically right {hr}% on {symbol} (n={rec['signals']})."
    elif hr >= 45:
        rating = "weak"; note = f"⚠️ Model only {hr}% on {symbol} historically (n={rec['signals']}) — coin-flip territory."
    else:
        rating = "poor"; note = f"⚠️ Model only {hr}% on {symbol} historically (n={rec['signals']}) — has been wrong more than right."
    return {"hit_rate": hr, "signals": rec["signals"], "rating": rating, "note": note}

